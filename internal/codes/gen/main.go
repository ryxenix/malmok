// Command gen renders the diagnostic code registry as markdown.
//
// Invoked by `go generate ./internal/codes/`. The output is a build artifact:
// editing it by hand is pointless because the next generate run overwrites it,
// and CLAUDE.md forbids a hand-maintained registry document precisely so that
// the markdown can never disagree with the code.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"platform.ryxen.dev/malmok/internal/codes"
)

func main() {
	out := flag.String("out", "", "path to write the markdown registry to (required)")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "gen: -out is required")
		os.Exit(2)
	}

	if errs := codes.Validate(); len(errs) > 0 {
		for _, err := range errs {
			fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		}
		os.Exit(1)
	}

	if err := os.WriteFile(*out, Render(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

// familyTitle maps a family to its section heading and the document that owns
// its definitions.
var familyTitle = map[codes.Family]struct{ name, source string }{
	codes.FamilyPreflight:    {"PF · Preflight", "docs/10-preflight-plan.md, docs/20-cert.md §4"},
	codes.FamilyVerification: {"PV · Post-apply verification", "docs/20-cert.md §6.5"},
	codes.FamilyExecution:    {"EX · Execution failures", "docs/11-execute.md §6"},
	codes.FamilyMaintenance:  {"MC · Maintenance checks", "docs/30-maintenance.md §3"},
	codes.FamilyDowngrade:    {"DG · Downgrade reasons", "docs/10-preflight-plan.md"},
}

// Render produces the whole document. Split out from main so main_test.go can
// diff it against the committed file — a package outside this one could not,
// since nothing may import a main package.
func Render() []byte {
	var b bytes.Buffer

	b.WriteString("<!-- Code generated by `go generate ./internal/codes/`. DO NOT EDIT. -->\n\n")
	b.WriteString("# malmok — diagnostic code registry\n\n")
	b.WriteString("Generated from `internal/codes/`, which is the single source of truth.\n")
	b.WriteString("Editing this file has no effect; change the Go definitions and re-run\n")
	b.WriteString("`go generate ./internal/codes/`.\n\n")
	b.WriteString("Codes are stable identifiers. They are never translated and never reused:\n")
	b.WriteString("a retired number stays retired, because audit reports and customer tickets\n")
	b.WriteString("outlive releases.\n\n")

	// Summary table first — the question people arrive with is usually "how
	// many of these block an install", not "what is PF-407".
	b.WriteString("## Summary\n\n")
	b.WriteString("| Family | Codes | block | degrade | warn | info |\n")
	b.WriteString("|---|--:|--:|--:|--:|--:|\n")
	for _, f := range codes.Families {
		cs := codes.ByFamily(f)
		n := map[codes.Severity]int{}
		for _, c := range cs {
			n[c.Severity]++
		}
		b.WriteString(fmt.Sprintf("| `%s` | %d | %s | %s | %s | %s |\n",
			f, len(cs),
			count(n[codes.SeverityBlock]), count(n[codes.SeverityDegrade]),
			count(n[codes.SeverityWarn]), count(n[codes.SeverityInfo])))
	}
	b.WriteString(fmt.Sprintf("\nTotal: %d codes.\n", len(codes.All())))

	for _, f := range codes.Families {
		cs := codes.ByFamily(f)
		if len(cs) == 0 {
			continue
		}
		title := familyTitle[f]
		b.WriteString(fmt.Sprintf("\n---\n\n## %s\n\n", title.name))
		b.WriteString(fmt.Sprintf("Source: %s\n", title.source))

		severed := f == codes.FamilyPreflight || f == codes.FamilyVerification ||
			f == codes.FamilyExecution
		if !severed {
			b.WriteString("\nThese codes carry no severity — see `internal/codes/codes.go`.\n")
		}

		for _, cat := range codes.Categories(f) {
			b.WriteString(fmt.Sprintf("\n### %s\n\n", cat))
			if severed {
				b.WriteString("| ID | Severity | Check | Default message |\n|---|---|---|---|\n")
			} else {
				b.WriteString("| ID | Item | Default message |\n|---|---|---|\n")
			}
			for _, c := range cs {
				if c.Category != cat {
					continue
				}
				if severed {
					b.WriteString(fmt.Sprintf("| `%s` | %s | %s | %s |\n",
						c.ID, c.Severity, esc(c.Summary), esc(c.Message)))
				} else {
					b.WriteString(fmt.Sprintf("| `%s` | %s | %s |\n",
						c.ID, esc(c.Summary), esc(c.Message)))
				}
			}
		}

		// Sub-codes are printed separately rather than crammed into the table:
		// they only exist for a handful of codes and they matter most when
		// somebody is reading a failure, not when scanning the catalogue.
		var withReasons []codes.Code
		for _, c := range cs {
			if len(c.Reasons) > 0 {
				withReasons = append(withReasons, c)
			}
		}
		if len(withReasons) > 0 {
			b.WriteString("\n#### Sub-codes\n\n| ID | Reasons |\n|---|---|\n")
			for _, c := range withReasons {
				quoted := make([]string, len(c.Reasons))
				for i, r := range c.Reasons {
					quoted[i] = "`" + r + "`"
				}
				b.WriteString(fmt.Sprintf("| `%s` | %s |\n", c.ID, strings.Join(quoted, ", ")))
			}
		}
	}

	return b.Bytes()
}

func count(n int) string {
	if n == 0 {
		return "—"
	}
	return fmt.Sprint(n)
}

// esc protects the table layout from pipes in message text.
func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
